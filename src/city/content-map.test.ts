import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { dropHeld, publicClaims } from "../lib/ledger";
import { claims as claimsSchema } from "../lib/schema";
import { cityContentMap, type CityContentMap } from "./content-map";

// ROADMAP-v4 P31.2. The test reads content/ the way the build does (the loader's own filter, then
// the schema) to get exactly the ledger's entries; city code itself never reads claims.json.
const raw = JSON.parse(readFileSync("content/claims.json", "utf8")) as { id: string; kind: string; visibility?: string }[];
const ledger = claimsSchema.parse(dropHeld(raw));
const risks = (JSON.parse(readFileSync("content/risks.json", "utf8")) as unknown[]).length;
const map = cityContentMap(ledger, risks);
const ledgerRows = publicClaims(ledger);

describe("city content map", () => {
  it("every entry the ledger shows has exactly one plot; the classified one is the Vault", () => {
    for (const c of ledgerRows) {
      if (c.kind === "classified") {
        expect(map.vault?.id).toBe(c.id);
        expect(map.plots.some((p) => p.id === c.id)).toBe(false);
      } else {
        expect(map.plots.filter((p) => p.id === c.id), c.id).toHaveLength(1);
      }
    }
    expect(map.plots).toHaveLength(ledgerRows.filter((c) => c.kind !== "classified").length);
    expect(new Set(map.plots.map((p) => p.plot)).size).toBe(map.plots.length);
  });

  it("a held entry never appears in city data, even if handed in unfiltered", () => {
    const source = raw.find((c) => c.kind !== "classified" && c.visibility !== "hold")!;
    const held = { ...source, id: "role-held-city-test", visibility: "hold" };
    const unfiltered = claimsSchema.parse([...raw, held]);
    const data = JSON.stringify(cityContentMap(unfiltered, risks));
    expect(data).not.toContain("role-held-city-test");
    // Nor any real held id, should one be added to content/ later.
    for (const c of raw.filter((x) => x.visibility === "hold")) expect(JSON.stringify(map)).not.toContain(c.id);
  });

  it("the Vault carries no text of the classified entry, only its id", () => {
    expect(map.vault && Object.keys(map.vault).sort()).toEqual(["id", "plot"]);
  });

  it("landmarks only for dossier parts that exist", () => {
    const empty = cityContentMap([], 0);
    expect(empty).toEqual({ plots: [], vault: null, landmarks: [] } satisfies CityContentMap);
    expect(map.landmarks.map((l) => l.id)).toContain("archive-tower");
    expect(map.landmarks.some((l) => l.id === "risk-registry")).toBe(risks > 0);
  });

  it("city code never reads content/claims.json", () => {
    const files: string[] = [];
    const walk = (dir: string): void => {
      for (const name of readdirSync(dir)) {
        const p = join(dir, name);
        if (statSync(p).isDirectory()) walk(p);
        else if (/\.(ts|astro|mjs)$/.test(name) && !/\.test\.ts$/.test(name)) files.push(p);
      }
    };
    for (const dir of ["src/city", join("src", "pages", "[lang]", "city")]) if (existsSync(dir)) walk(dir);
    for (const f of files) expect(readFileSync(f, "utf8"), f).not.toMatch(/claims\.json/);
  });
});

// docs/city/content-map.md is written from the same map (`pnpm city:content-map`), and this test
// fails while it is out of date, so the document always matches the build.
export function contentMapDoc(m: CityContentMap): string {
  const rows = m.plots.map((p) => `| ${p.id} | ${p.plot} | ${p.kind} | ${p.domains.join(", ") || "-"} | ${p.tier} | ${p.place ?? "-"} |`);
  return [
    "# Agent T City — content map",
    "",
    "Generated by `pnpm city:content-map` from the filtered dossier data (the entries the ledger renders; `hold` entries never appear). Do not edit by hand: `src/city/content-map.test.ts` fails when this file is out of date.",
    "",
    "## Plots (one per open entry)",
    "",
    "| Entry id | Plot | Kind | Domains | Tier | Place |",
    "|---|---|---|---|---|---|",
    ...rows,
    "",
    "## Vault",
    "",
    m.vault ? `| ${m.vault.id} | ${m.vault.plot} | type label only |` : "No classified entry.",
    ...(m.vault ? ["", "Columns: entry id, plot, what the city may show."] : []),
    "",
    "## Landmarks (dossier parts that exist)",
    "",
    "| Landmark | Dossier component |",
    "|---|---|",
    ...m.landmarks.map((l) => `| ${l.id} | ${l.component} |`),
    "",
  ].join("\n");
}

describe("docs/city/content-map.md", () => {
  it("matches the content map", () => {
    const doc = contentMapDoc(map);
    if (process.env["WRITE_CONTENT_MAP"]) writeFileSync(join("docs", "city", "content-map.md"), doc);
    expect(readFileSync(join("docs", "city", "content-map.md"), "utf8").replace(/\r\n/g, "\n")).toBe(doc);
  });
});
