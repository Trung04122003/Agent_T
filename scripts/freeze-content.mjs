// Content freeze (ROADMAP 19.3). Records a SHA-256 of every file in content/ (line endings
// normalised, so Windows checkouts hash the same) in docs/content-freeze.json, and writes the
// line-by-line reconciliation of every entry with its approval to docs/content-freeze.md.
// A unit test fails while content/ differs from the freeze: change content only on purpose, then
// re-run this with the owner's go-ahead.
// Usage: node scripts/freeze-content.mjs
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { approvalFor } from "../src/lib/approval.ts";
import { tierOf } from "../src/lib/evidence.ts";

const root = resolve(fileURLToPath(import.meta.url), "..", "..");
const contentDir = join(root, "content");
export const FREEZE_FILE = join(root, "docs", "content-freeze.json");

/** SHA-256 of each content/*.json, LF line endings. */
export function contentHashes() {
  const out = {};
  for (const name of readdirSync(contentDir).filter((n) => n.endsWith(".json")).sort()) {
    const text = readFileSync(join(contentDir, name), "utf8").replace(/\r\n/g, "\n");
    out[name] = createHash("sha256").update(text).digest("hex");
  }
  return out;
}

/** One line per entry: what shows, and on what approval. */
export function reconcile() {
  const claims = JSON.parse(readFileSync(join(contentDir, "claims.json"), "utf8"));
  return claims.map((c) => {
    if (c.kind === "classified") {
      return { id: c.id, shows: "label only", status: c.status, org: c.label.vi, approval: "-", tier: "-", blocks: "-" };
    }
    const needs = approvalFor(c);
    const approval = needs ? (c.approval ? `${needs}: ${c.approval.by}, ${c.approval.on}` : `${needs}: MISSING`) : "not needed";
    const blocks = [c.bluf && "BLUF", c.tearSheet && "tear sheet", c.aar && "AAR"].filter(Boolean).join(", ") || "-";
    return {
      id: c.id,
      shows: c.visibility === "hold" ? "HOLD (never built)" : "open",
      status: c.status,
      org: c.org?.vi ?? c.title?.vi ?? "(none)",
      approval,
      tier: tierOf(c.evidence ?? []),
      blocks,
    };
  });
}

function markdown(rows, frozenOn) {
  const lines = [
    "# Content freeze (ROADMAP 19.3)",
    "",
    `Generated by \`pnpm freeze:content\` on ${frozenOn}. Do not edit by hand.`,
    "",
    "| id | Shows | Status | Org / title (vi) | Approval | Evidence | Owner blocks |",
    "|---|---|---|---|---|---|---|",
    ...rows.map((r) => `| ${r.id} | ${r.shows} | ${r.status} | ${r.org} | ${r.approval} | ${r.tier} | ${r.blocks} |`),
    "",
    "Rules checked: an open entry from an organisation that must approve (src/lib/approval.ts) needs",
    "`approval: { by, on }`; hold entries are never built; classified entries show their label only.",
    "",
  ];
  return lines.join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const frozenOn = new Date().toISOString().slice(0, 10);
  const rows = reconcile();
  const missing = rows.filter((r) => r.shows === "open" && r.approval.endsWith("MISSING"));
  if (missing.length) {
    console.error(`freeze-content: open entries without approval: ${missing.map((r) => r.id).join(", ")}`);
    process.exit(1);
  }
  writeFileSync(FREEZE_FILE, JSON.stringify({ frozenOn, files: contentHashes() }, null, 2) + "\n");
  writeFileSync(join(root, "docs", "content-freeze.md"), markdown(rows, frozenOn));
  console.log(`freeze-content: ${Object.keys(contentHashes()).length} file(s) frozen, ${rows.length} entr(ies) reconciled.`);
}
